const PATTERNS = TERMS.map((t) => ({
  term: t,
  // Whole words only, so "marionette" is not caught by "mario" and "stitch" stays usable.
  re: new RegExp(
    `(^|[^\\p{L}\\p{N}])${t.replace(/[.*+?^${}()|[\]\\]/g, "\\$&")}($|[^\\p{L}\\p{N}])`,
    "iu",
  ),
}));

/** Returns the first protected term found in the text, or null. */
export function findProtectedTerm(text: string): string | null {
  for (const { term, re } of PATTERNS) if (re.test(text)) return term;
  return null;
}

